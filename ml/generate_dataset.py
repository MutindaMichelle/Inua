"""
INUA Mentorship Platform: Synthetic Dataset Generator (Pre-Session & Outcome Bootstrapping)
Author: Michelle (Final Year Project - BICS Year 4, Strathmore University)
Use Case: U-CS 5 (session-value) — Career Mentor OS

Academic Foundation:
- Kram, K. E. (1985). Mentoring at work: Developmental relationships in organizational life.
- Noe, R. A. (1988). An investigation of the determinants of successful assigned mentoring relationships.
- Scandura, T. A., & Ragins, B. R. (1993). The effects of sex and gender role orientation on mentorship.
- Allen, T. D., et al. (2004). Career benefits associated with mentoring for proteges: A meta-analysis.
- Bandura, A. (1997). Self-efficacy: The exercise of control.

IMPORTANT — SYNTHETIC DATA NOTICE:
All records generated by this module are 100% SYNTHETIC (`isSynthetic = True`).
Ground-truth binary outcome `session_effectiveness` (Y in {0, 1}) is derived offline
using a composite post-session construct threshold (>= 3.8 / 5.0, or >= 0.76 utility)
per Noe (1988) and Scandura & Ragins (1993).
At training and inference time, ONLY pre-session features (X) known BEFORE the session
takes place (`leadTimeHours`, `hasAgenda`, `isFirstSession`, `mentor_experience_years`,
`prior_sessions`, and dyad profile attributes) are used.
"""

import os
import math
import random
import csv
from datetime import datetime, timedelta, timezone

try:
    import numpy as np
    import pandas as pd
    HAS_PANDAS = True
except ImportError:
    HAS_PANDAS = False


def set_seed(seed: int = 42):
    """Initializes deterministic random state for reproducible synthesis."""
    random.seed(seed)
    if HAS_PANDAS:
        return np.random.default_rng(seed)
    return None


def generate_student_profile(n_samples: int, rng=None) -> list:
    """
    Generates mentee demographic and baseline academic characteristics.
    Probabilities are calibrated to Strathmore undergraduate academic demographics.
    """
    career_stages = ["Year1", "Year2", "Year3", "Year4", "Graduate", "EarlyCareer"]
    stage_probs = [0.125, 0.160, 0.210, 0.240, 0.140, 0.125]

    fields_of_study = [
        "Computer Science",
        "Engineering",
        "Business",
        "Data Analytics",
        "Health Sciences",
        "Education",
        "Social Sciences",
        "Other STEM",
    ]
    field_probs = [0.21, 0.16, 0.15, 0.11, 0.09, 0.07, 0.06, 0.15]

    career_interests = [
        "Data Science",
        "Software Engineering",
        "Cybersecurity",
        "Artificial Intelligence",
        "Cloud Computing",
        "UI/UX",
        "Product Management",
        "Finance",
        "Entrepreneurship",
    ]
    interest_probs = [0.17, 0.18, 0.11, 0.13, 0.10, 0.09, 0.08, 0.08, 0.06]

    students = []
    for _ in range(n_samples):
        stage = random.choices(career_stages, weights=stage_probs, k=1)[0]
        field = random.choices(fields_of_study, weights=field_probs, k=1)[0]
        interest = random.choices(career_interests, weights=interest_probs, k=1)[0]

        # Prior sessions (historical_interaction_frequency): Poisson-like (range 0 to 12)
        lam = 2.2
        L = math.exp(-lam)
        k = 0
        p = 1.0
        while p > L:
            k += 1
            p *= random.random()
        prior_sessions = max(0, min(12, k - 1))
        is_first_session = 1 if prior_sessions == 0 else 0

        students.append({
            "career_stage": stage,
            "field_of_study": field,
            "career_interest": interest,
            "prior_sessions": prior_sessions,
            "isFirstSession": is_first_session,
        })

    return students


def generate_mentor_profile(n_samples: int, rng=None) -> list:
    """Generates mentor professional attributes and availability indicators."""
    industries = [
        "Technology",
        "Banking & Finance",
        "Academia",
        "Healthcare",
        "NGO",
        "Government",
        "Entrepreneurship",
    ]
    industry_probs = [0.28, 0.16, 0.14, 0.10, 0.10, 0.08, 0.14]

    availabilities = ["High", "Medium", "Low"]
    availability_probs = [0.35, 0.45, 0.20]

    specialization_map = {
        "Technology": ["Cloud Architecture", "Backend Engineering", "AI Systems", "Cyber Defense", "Full Stack Dev"],
        "Banking & Finance": ["Financial Modeling", "Fintech Innovations", "Risk Management", "Investment Banking"],
        "Academia": ["Postgraduate Research", "Scientific Writing", "Doctoral Pathways", "Applied Statistics"],
        "Healthcare": ["Health Informatics", "Biomedical Systems", "Public Health Research"],
        "NGO": ["Program Evaluation", "Development Policy", "Sustainable Tech"],
        "Government": ["Public Sector ICT", "E-Governance", "Digital Infrastructure"],
        "Entrepreneurship": ["Tech Venture Building", "Product Strategy", "Seed Fundraising", "Go-to-Market"],
    }

    mentors = []
    for _ in range(n_samples):
        industry = random.choices(industries, weights=industry_probs, k=1)[0]
        specialization = random.choice(specialization_map[industry])
        availability = random.choices(availabilities, weights=availability_probs, k=1)[0]

        raw_exp = random.gammavariate(2.8, 3.2)
        exp_years = max(1, min(25, round(raw_exp)))

        mentors.append({
            "mentor_experience_years": exp_years,
            "mentor_industry": industry,
            "mentor_specialization": specialization,
            "mentor_availability": availability,
        })

    return mentors


def generate_session(students: list, mentors: list, rng=None) -> list:
    """
    Synthesizes pre-session booking context (created_at, leadTimeHours, hasAgenda)
    and session parameters.
    """
    n_samples = len(students)

    session_types = [
        "Career Guidance",
        "CV Review",
        "Interview Preparation",
        "Technical Coaching",
        "Networking",
    ]

    stage_to_session_probs = {
        "Year1": [0.50, 0.15, 0.05, 0.05, 0.25],
        "Year2": [0.35, 0.35, 0.05, 0.15, 0.10],
        "Year3": [0.10, 0.30, 0.20, 0.35, 0.05],
        "Year4": [0.10, 0.25, 0.40, 0.20, 0.05],
        "Graduate": [0.15, 0.20, 0.45, 0.10, 0.10],
        "EarlyCareer": [0.25, 0.10, 0.20, 0.20, 0.25],
    }

    goal_categories = [
        "Internship",
        "Portfolio Development",
        "Technical Skills",
        "Career Transition",
        "Leadership",
        "Research",
    ]

    stage_to_goal_probs = {
        "Year1": [0.15, 0.15, 0.30, 0.10, 0.15, 0.15],
        "Year2": [0.35, 0.25, 0.25, 0.05, 0.05, 0.05],
        "Year3": [0.45, 0.25, 0.20, 0.03, 0.03, 0.04],
        "Year4": [0.30, 0.30, 0.20, 0.10, 0.05, 0.05],
        "Graduate": [0.10, 0.25, 0.15, 0.35, 0.10, 0.05],
        "EarlyCareer": [0.05, 0.15, 0.15, 0.35, 0.25, 0.05],
    }

    duration_params = {
        "Career Guidance": {"mean": 55, "std": 8, "min": 40, "max": 70},
        "CV Review": {"mean": 45, "std": 7, "min": 30, "max": 60},
        "Interview Preparation": {"mean": 65, "std": 10, "min": 45, "max": 90},
        "Technical Coaching": {"mean": 85, "std": 15, "min": 60, "max": 120},
        "Networking": {"mean": 30, "std": 6, "min": 20, "max": 45},
    }

    platforms = ["Teams", "Zoom", "Meet", "Physical"]
    platform_probs = [0.35, 0.30, 0.20, 0.15]

    base_start = datetime(2025, 1, 1, 8, 0, 0, tzinfo=timezone.utc)
    sessions = []

    for i in range(n_samples):
        stage = students[i]["career_stage"]
        prior = students[i]["prior_sessions"]
        avail = mentors[i]["mentor_availability"]
        exp = mentors[i]["mentor_experience_years"]

        s_type = random.choices(session_types, weights=stage_to_session_probs[stage], k=1)[0]
        goal = random.choices(goal_categories, weights=stage_to_goal_probs[stage], k=1)[0]

        cfg = duration_params[s_type]
        duration = int(random.gauss(cfg["mean"], cfg["std"]))
        duration = max(cfg["min"], min(cfg["max"], duration))

        # Pre-session booking lead time (hours before scheduled session)
        if avail == "High" or prior >= 2:
            lead_time_hours = int(max(4, min(168, random.gauss(56, 24))))
        elif avail == "Medium":
            lead_time_hours = int(max(2, min(168, random.gauss(34, 20))))
        else:
            lead_time_hours = int(max(1, min(120, random.gauss(16, 14))))

        # Whether mentee submitted a structured agenda before the session
        agenda_prob = 0.28
        if lead_time_hours >= 24:
            agenda_prob += 0.32
        if prior >= 1:
            agenda_prob += 0.18
        if exp >= 5:
            agenda_prob += 0.10
        if avail == "Low":
            agenda_prob -= 0.18
        agenda_prob = max(0.08, min(0.92, agenda_prob))
        has_agenda = 1 if random.random() < agenda_prob else 0

        # Attendance outcome (post-session, influenced by pre-session readiness)
        if has_agenda == 1 and lead_time_hours >= 24:
            att_probs = [0.92, 0.06, 0.02]
        elif has_agenda == 1 or lead_time_hours >= 24:
            att_probs = [0.80, 0.13, 0.07]
        else:
            att_probs = [0.55, 0.25, 0.20]
        attendance = random.choices(["Attended", "Rescheduled", "Cancelled"], weights=att_probs, k=1)[0]

        platform = random.choices(platforms, weights=platform_probs, k=1)[0]

        # Monotonically increasing timestamp for chronological train/test splitting
        created_dt = base_start + timedelta(hours=i * 6 + random.randint(0, 4), minutes=random.randint(0, 59))
        created_at = created_dt.strftime("%Y-%m-%dT%H:%M:%SZ")

        sessions.append({
            "session_id": f"INUA_SESS_{i+1:04d}",
            "created_at": created_at,
            "leadTimeHours": lead_time_hours,
            "hasAgenda": has_agenda,
            "session_type": s_type,
            "session_duration_minutes": duration,
            "attendance_status": attendance,
            "meeting_platform": platform,
            "goal_category": goal,
        })

    return sessions


def generate_scores(students: list, sessions: list, mentors: list, rng=None) -> list:
    """
    Computes post-session Likert ratings (1-5) used ONLY offline to bootstrap ground-truth Y.
    Grounded in Noe (1988) and Scandura & Ragins (1993) mentorship functions.
    """
    n_samples = len(sessions)
    scores = []

    for i in range(n_samples):
        attendance = sessions[i]["attendance_status"]
        has_agenda = sessions[i]["hasAgenda"]
        lead_hours = sessions[i]["leadTimeHours"]
        prior = students[i]["prior_sessions"]
        is_first = students[i]["isFirstSession"]
        exp_years = mentors[i]["mentor_experience_years"]
        avail = mentors[i]["mentor_availability"]

        if attendance == "Cancelled":
            scores.append({
                "career_support_score": 1,
                "psychosocial_support_score": 1,
                "communication_quality": 1,
                "goal_progress_score": 1,
                "confidence_growth_score": 1,
                "mentor_responsiveness_score": 1,
            })
            continue

        # Pre-session readiness + non-linear dyad interaction signal driving session quality
        prep_bonus = 0.0
        if has_agenda == 1:
            prep_bonus += 0.48
        else:
            prep_bonus -= 0.42

        if lead_hours >= 24:
            prep_bonus += 0.32
        elif lead_hours < 12:
            prep_bonus -= 0.45

        if prior >= 2:
            prep_bonus += 0.45
        elif is_first == 1:
            prep_bonus -= 0.30

        # Non-linear interaction: experienced mentor + prepared mentee + high availability
        if exp_years >= 6 and avail == "High":
            prep_bonus += 0.45
        elif exp_years <= 2 and avail == "Low":
            prep_bonus -= 0.55

        if has_agenda == 1 and prior == 0 and avail == "Low":
            # Agenda alone isn't enough when first session with low-availability novice mentor
            prep_bonus -= 0.55
        if has_agenda == 0 and prior >= 3 and exp_years >= 7 and avail == "High":
            # Established dyads with senior mentors succeed even without formal agenda
            prep_bonus += 0.65

        avail_bonus = {"High": 0.50, "Medium": 0.05, "Low": -0.65}[avail]

        # Mentor responsiveness (1-5)
        mu_resp = 3.2 + avail_bonus + 0.30 * has_agenda + (0.20 if lead_hours >= 24 else -0.25) + 0.04 * exp_years
        resp_score = max(1, min(5, round(random.gauss(mu_resp, 0.32))))

        # Career support (Noe, 1988): driven by mentor experience + agenda + lead time + dyad history
        mu_career = 1.95 + 0.68 * math.log(exp_years + 1.0) + prep_bonus
        c_score = max(1, min(5, round(random.gauss(mu_career, 0.32))))

        # Communication quality
        mu_comm = 2.75 + 0.38 * (resp_score - 3) + 0.45 * has_agenda + 0.22 * min(prior, 4)
        comm_score = max(1, min(5, round(random.gauss(mu_comm, 0.32))))

        # Psychosocial support (Scandura & Ragins, 1993)
        mu_psycho = 0.65 + 0.82 * comm_score + 0.16 * min(prior, 3)
        p_score = max(1, min(5, round(random.gauss(mu_psycho, 0.30))))

        # Goal progress score
        mu_goal = 0.45 * c_score + 0.30 * comm_score + 0.25 * resp_score + (0.25 if has_agenda else -0.20)
        g_score = max(1, min(5, round(random.gauss(mu_goal, 0.30))))

        # Confidence growth score (Bandura, 1997)
        mu_conf = 0.50 * p_score + 0.35 * g_score + 0.15 * comm_score
        conf_score = max(1, min(5, round(random.gauss(mu_conf, 0.30))))

        if attendance == "Rescheduled":
            resp_score = max(1, resp_score - 1)
            g_score = max(1, g_score - 1)

        scores.append({
            "career_support_score": c_score,
            "psychosocial_support_score": p_score,
            "communication_quality": comm_score,
            "goal_progress_score": g_score,
            "confidence_growth_score": conf_score,
            "mentor_responsiveness_score": resp_score,
        })

    return scores


def calculate_effectiveness(sessions: list, scores: list, rng=None) -> list:
    """
    Derives Ground-Truth Outcome (Y) offline during synthetic bootstrapping:
    - Composite score on 5-point scale using Noe (1988) and Scandura & Ragins (1993) constructs.
    - Literature threshold: composite >= 3.8 / 5.0 (i.e. normalized index >= 0.76).
    """
    n_samples = len(sessions)
    outcomes = []

    w_goal = 0.25
    w_career = 0.20
    w_conf = 0.20
    w_comm = 0.15
    w_psycho = 0.10
    w_resp = 0.10

    for i in range(n_samples):
        attendance = sessions[i]["attendance_status"]

        if attendance == "Cancelled":
            idx = round(random.uniform(0.05, 0.22), 4)
            label = 0
        else:
            sc = scores[i]
            composite_5pt = (
                w_goal * sc["goal_progress_score"]
                + w_career * sc["career_support_score"]
                + w_conf * sc["confidence_growth_score"]
                + w_comm * sc["communication_quality"]
                + w_psycho * sc["psychosocial_support_score"]
                + w_resp * sc["mentor_responsiveness_score"]
            )
            idx = max(0.10, min(0.99, (composite_5pt / 5.0) + random.gauss(0, 0.015)))
            idx = round(idx, 4)

            # Literature threshold: composite >= 3.8 / 5.0 (0.76 normalized utility)
            label = 1 if (composite_5pt >= 3.8 and attendance == "Attended") else 0

        outcomes.append({
            "effectiveness_index": idx,
            "session_effectiveness": label,
        })

    return outcomes


def create_dataset(n: int = 2000, random_state: int = 42, output_path: str = None):
    """Coordinates modular synthesis, verifies invariants, and exports CSV."""
    print(f"[INUA] Initializing synthetic mentorship dataset generation (n={n}, seed={random_state})...")
    rng = set_seed(random_state)

    students = generate_student_profile(n, rng)
    mentors = generate_mentor_profile(n, rng)
    sessions = generate_session(students, mentors, rng)
    scores = generate_scores(students, sessions, mentors, rng)
    outcomes = calculate_effectiveness(sessions, scores, rng)

    column_order = [
        "session_id",
        "created_at",
        "leadTimeHours",
        "hasAgenda",
        "isFirstSession",
        "career_stage",
        "field_of_study",
        "career_interest",
        "prior_sessions",
        "mentor_experience_years",
        "mentor_industry",
        "mentor_specialization",
        "mentor_availability",
        "session_type",
        "session_duration_minutes",
        "attendance_status",
        "meeting_platform",
        "goal_category",
        "career_support_score",
        "psychosocial_support_score",
        "communication_quality",
        "goal_progress_score",
        "confidence_growth_score",
        "mentor_responsiveness_score",
        "effectiveness_index",
        "session_effectiveness",
    ]

    rows = []
    for i in range(n):
        record = {}
        record.update(students[i])
        record.update(mentors[i])
        record.update(sessions[i])
        record.update(scores[i])
        record.update(outcomes[i])
        ordered_record = {col: record[col] for col in column_order}
        rows.append(ordered_record)

    assert len(rows) == n, f"Expected {n} rows, got {len(rows)}"

    pos_count = sum(1 for r in rows if r["session_effectiveness"] == 1)
    pos_rate = pos_count / n

    print(f"[INUA] Synthetic dataset synthesis completed (isSynthetic=True)!")
    print(f"       Total rows: {len(rows)}")
    print(f"       Total columns: {len(column_order)}")
    print(f"       Effective sessions (1): {pos_count} ({pos_rate:.1%})")
    print(f"       Ineffective sessions (0): {n - pos_count} ({1 - pos_rate:.1%})")

    if output_path:
        os.makedirs(os.path.dirname(output_path), exist_ok=True)
        with open(output_path, mode="w", newline="", encoding="utf-8") as f:
            writer = csv.DictWriter(f, fieldnames=column_order)
            writer.writeheader()
            writer.writerows(rows)
        print(f"[INUA] Successfully exported synthetic dataset to: {output_path}")

    if HAS_PANDAS:
        return pd.DataFrame(rows)
    return rows


if __name__ == "__main__":
    cur_dir = os.path.dirname(os.path.abspath(__file__))
    base_dir = os.path.dirname(cur_dir) if os.path.basename(cur_dir) == "scripts" else cur_dir
    target_csv = os.path.join(base_dir, "data", "inua_mentorship_dataset.csv")
    create_dataset(n=2000, random_state=42, output_path=target_csv)
